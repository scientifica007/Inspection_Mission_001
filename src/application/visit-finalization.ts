// Gate 5K — T11 `finalizeVisit` (runtime-neutral TypeScript, no node:*
// imports).
//
// Implements the adopted single-transaction preflight + finalization contract
// of TRANSACTION-CONTRACTS-v1.md §11 / APPLICATION-CORE-v1.md §4.10 + §8:
//
//   * ONE explicit BEGIN IMMEDIATE … COMMIT/ROLLBACK unit — absolutely no
//     read-only preflight outside the authoritative transaction (no TOCTOU
//     window): re-read the Visit → Class-A idempotent branch → ALL preflight
//     SELECT checks inside the SAME transaction → structured blockers ⇒
//     ROLLBACK → guarded final UPDATE (changes == 1, B5) → COMMIT.
//
//   * Visit precondition (inside BEGIN IMMEDIATE): missing Visit ⇒
//     E_VISIT_NOT_FOUND; not finalized but status <> 'PREPARATION' ⇒
//     E_VISIT_NOT_PREPARATION. A finalized Visit (finalized_at IS NOT NULL
//     AND status IN ('COMPLETED','COMPLETED_WITH_UNINSPECTED')) is handled by
//     the Class-A retry branch FIRST — never treated as an illegal mutable
//     state, never reopened, never re-finalized. The impossible combination
//     finalized_at NOT NULL + status 'PREPARATION' is a typed
//     E_STATE_CONFLICT (schema CHECK makes it unrepresentable at rest; the
//     branch exists so a fabricated/corrupt read never silently converges).
//
//   * Preflight (all SELECTs inside the same transaction; blockers are
//     collected, never auto-fixed):
//       1. E_SCOPE_GAP — expected cell set == actual cell set, where
//          expected = captured universe × captured contexts, both
//          reconstructed ONLY from durable Visit rows (institution-context
//          rows with their pinned item_definition_id values; contexts =
//          institution context + every distinct subject context durably
//          present in the grid). Current ACTIVE definitions are never
//          queried to discover codes; no silent repair. Missing cells,
//          extra/mismatched cells, partial subject grids, version/context
//          mismatches and an empty captured universe all surface as
//          E_SCOPE_GAP.
//       2. E_UNRESOLVED_PENDING — any cell in the true unresolved pending
//          state (overlay_state='NOT_INSPECTED', answered_value_id NULL,
//          not_inspected_reason NULL) survives; includes unresolved
//          HUMAN_CONFIRMATION cells. No pending cell may survive
//          finalization.
//       3. E_UNINSPECTED_NEEDS_REASON — every deliberate NOT_INSPECTED cell
//          that will survive into the finalized Visit carries a meaningful
//          (trimmed non-blank) reason. Never auto-filled.
//       4. E_NC_UNACCOUNTED — every answered cell whose selected allowed
//          value has semantic_class='NON_COMPLIANT' is linked to a Finding
//          (finding_id IS NOT NULL). Re-check; never linked here.
//       5. E_NC_NEEDS_NOTE — every NON_COMPLIANT answered cell carries a
//          meaningful (trimmed non-blank) note. Re-check; never written here.
//       6. E_CHK012 — the adopted SCHEDULE physical/domain invariants
//          re-checked for every response whose PINNED definition has
//          response_model='SCHEDULE' (generic durable discriminator — never
//          item_code switching): reconciliation rows belong only to SCHEDULE
//          responses; no overlay state coexists with rows; COMPLIANT overall
//          has no discrepancy row (difference <> 0 OR discrepancy_type NOT
//          NULL); difference = observed_qty - declared_qty; discrepancy_type
//          from the closed set with OTHER ⇒ non-blank description; category
//          meaningful. Rows are never mutated by T11.
//       7. E_ORPHAN_FINDING — a Finding with origin_visit_id = this Visit,
//          status 'OPEN', and zero recorded sources across BOTH
//          checklist_response AND adhoc_observation. VOIDED findings are
//          EXPECTED source-less and are never blockers; OPEN/IN_TREATMENT/
//          RESOLVED findings and CorrectiveActions of ANY status are never
//          finalization blockers (remediation continues after field-truth
//          finalization) and are never transitioned/created/closed by T11.
//
//   * Blockers ⇒ ROLLBACK + ONE DomainError whose top-level code is the
//     FIRST blocker's code in the deterministic §8 order and whose
//     `blockers` payload carries EVERY blocker (codes + durable
//     identifiers/context: responseId / itemDefinitionId / subjectId /
//     itemCode / findingId / rowId + machine-readable `kind`). Ordering is
//     deterministic for repeatable tests/UI. No Arabic display prose is
//     generated by the domain; codes + identifiers are the source of truth.
//
//   * Final status derivation (inside the SAME transaction, from durable
//     Visit rows only — never caller-chosen): any checklist_response with
//     overlay_state='NOT_INSPECTED' ⇒ 'COMPLETED_WITH_UNINSPECTED', else
//     'COMPLETED'. NA never counts as NOT_INSPECTED; Finding/Action status
//     never influences the choice.
//
//   * Guarded final UPDATE (B5):
//       UPDATE visit SET status = <derived>, finalized_at = <normalized>
//        WHERE visit_id = ? AND status = 'PREPARATION' AND finalized_at IS NULL
//     requiring changes == 1. On changes != 1: ROLLBACK FIRST, then re-read
//     the durable Visit — a valid finalized row converges as Class-A
//     idempotent success (applied:false; the DURABLE status/finalized_at are
//     returned — a retry's fresh finalizedAt parameter never rewrites the
//     durable timestamp and never recalculates the final status); anything
//     else ⇒ E_STATE_CONFLICT. Never COMMIT after zero affected rows.
//
//   * finalizedAt: app-supplied strict ISO-8601 UTC instant (the exact
//     Gate-5G/5H/5J convention — YYYY-MM-DDTHH:MM:SS[.fraction]Z, explicit
//     'Z', calendar-valid components, no local/timezone-less/offset forms,
//     never invented internally, never permissive Date.parse). Trimmed before
//     validate/store; the trimmed text is stored verbatim.
//
// Out of scope (later gates): currentVisitState, Mission finalization,
// Finding/CorrectiveAction transitions, observation correction, report
// generation, Evidence, ExternalSystemTracking, UI/sync/mobile.

